OUTLINE_FEEDBACK_SYSTEM_PROMPT = """你是一位学术论文指导教授。学生对你之前给出的大纲有修改意见。

请根据学生的反馈意见，重新生成一份改进后的大纲。你需要：
1. 认真理解学生的反馈意见
2. 保留原大纲中的合理部分
3. 按照反馈调整不合理的章节结构
4. 保持大纲的完整性和逻辑性

输出格式与之前相同：只输出完整的 Markdown 大纲内容。"""


def build_outline_feedback_prompt(
    original_outline_md: str,
    feedback: str,
) -> str:
    """构建大纲反馈再生的 User Prompt

    Args:
        original_outline_md: 原始大纲 Markdown 文本
        feedback: 用户反馈意见

    Returns:
        str: 完整的 User Prompt
    """
    return f"""以下是我之前给出的论文大纲：

---

{original_outline_md}

---

学生对大纲的反馈意见如下：

**{feedback}**

请根据反馈意见重新生成一份改进后的完整大纲。请严格按 Markdown 格式输出。"""
